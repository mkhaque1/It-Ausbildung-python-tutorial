# conditions in python , if,  else,  elif
# == equal to
# != not equal to
# >= greater than or equal to
# <= less than or equal to

name = 'khairul'
age = 9

if name == 'MK' and age == 30:
    print('Name is MK and age is 30')
elif name == 'MK' and age != 30:
    print('Name is MK but age is not 30')
else:
    print('Name is not MK')


if age >= 18:
    print(name + ' is an adult')
else:
    print(name + ' is not an adult')

