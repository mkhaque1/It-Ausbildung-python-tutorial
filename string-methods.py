# str methods

#capitalize()

name = 'mkhaque'

capitalize_name = name.capitalize()

print(capitalize_name)

# upper() / lower()

upper_name = name.upper()
lower_name = name.lower()
print(upper_name)

# title()

title_name = name.title()
print(title_name)

#encode() / decode()

encode = name.encode('utf-8')
print(encode)

decode = encode.decode('utf-8')
print(decode)
